import { describe, expect, test } from 'vitest';

import {
  claudeNoteLines,
  claudeRules,
  codexRulesFile,
  codexTokens,
  copilotRegionLines,
  copilotRule,
  opencodeRegionLines,
  wrapText,
} from '../../../../lib/node/agents-config/shell-emitters.ts';
import type {
  ShellPermissionEntry,
  ShellPermissionList,
} from '../../../../lib/node/agents-config/shell-permissions.ts';

const LIST: ShellPermissionList = {
  entries: [
    { pattern: 'cp *', tier: 'extras' },
    { pattern: 'find *', tier: 'shared', note: '`-exec` runs commands.', copilot: 'readonly' },
    { pattern: 'git log*', tier: 'shared' },
    { pattern: 'git remote', tier: 'shared', copilot: 'readonly', codex: 'broader' },
    { pattern: 'jq *', tier: 'shared', note: 'Reads JSON.' },
    { pattern: 'kubectl logs *', tier: 'shared', copilot: 'broader' },
    { pattern: 'npm -v', tier: 'shared' },
    { pattern: 'yq *', tier: 'shared', except: ['yq -i *', 'yq * -i *'] },
  ],
};

function entry(pattern: string): ShellPermissionEntry {
  const found = LIST.entries.find((e) => e.pattern === pattern);
  if (!found) throw new Error(`no fixture entry ${pattern}`);
  return found;
}

describe('wrapText', () => {
  test('keeps short text on one line', () => {
    expect(wrapText('a b c', '# ', '# ')).toEqual(['# a b c']);
  });

  test('wraps greedily at the width with the continuation prefix', () => {
    expect(wrapText('aaa bbb ccc ddd', '- ', '  ', 10)).toEqual(['- aaa bbb', '  ccc ddd']);
  });

  test('never breaks inside a backtick code span', () => {
    expect(wrapText('see `find *` here', '', '', 8)).toEqual(['see', '`find *`', 'here']);
  });
});

describe('claudeRules', () => {
  test('allows every entry of both tiers and asks for every except glob', () => {
    expect(claudeRules(LIST)).toEqual({
      allow: [
        'Bash(cp *)',
        'Bash(find *)',
        'Bash(git log*)',
        'Bash(git remote)',
        'Bash(jq *)',
        'Bash(kubectl logs *)',
        'Bash(npm -v)',
        'Bash(yq *)',
      ],
      ask: ['Bash(yq -i *)', 'Bash(yq * -i *)'],
    });
  });

  test('notes become markdown bullets', () => {
    expect(claudeNoteLines(LIST)).toEqual(['- `find *`: `-exec` runs commands.', '- `jq *`: Reads JSON.']);
  });
});

describe('opencodeRegionLines', () => {
  test('shared allows with note comments, then except asks', () => {
    expect(opencodeRegionLines(LIST, '  ')).toEqual([
      '  // `-exec` runs commands.',
      '  { "action": "shell", "resource": "find *", "effect": "allow" },',
      '  { "action": "shell", "resource": "git log*", "effect": "allow" },',
      '  { "action": "shell", "resource": "git remote", "effect": "allow" },',
      '  // Reads JSON.',
      '  { "action": "shell", "resource": "jq *", "effect": "allow" },',
      '  { "action": "shell", "resource": "kubectl logs *", "effect": "allow" },',
      '  { "action": "shell", "resource": "npm -v", "effect": "allow" },',
      '  { "action": "shell", "resource": "yq *", "effect": "allow" },',
      '  // `except` globs: ask even though an allow rule above matches (the last matching rule wins).',
      '  { "action": "shell", "resource": "yq -i *", "effect": "ask" },',
      '  { "action": "shell", "resource": "yq * -i *", "effect": "ask" },',
    ]);
  });

  test('no ask comment without except globs', () => {
    expect(opencodeRegionLines({ entries: [{ pattern: 'ls *', tier: 'shared' }] })).toEqual([
      '    { "action": "shell", "resource": "ls *", "effect": "allow" },',
    ]);
  });
});

describe('copilot', () => {
  test.each([
    ['cp *', undefined], // extras
    ['find *', undefined], // readonly tier
    ['git log*', undefined], // glued wildcard
    ['kubectl logs *', undefined], // broader identifier
    ['yq *', undefined], // except
    ['jq *', 'shell(jq:*)'],
    ['npm -v', 'shell(npm -v)'],
  ])('copilotRule(%s) = %s', (pattern, expected) => {
    expect(copilotRule(entry(pattern))).toBe(expected);
  });

  test('region lines carry notes as # comments', () => {
    expect(copilotRegionLines(LIST)).toEqual(['# Reads JSON.', 'allow shell(jq:*)', 'allow shell(npm -v)']);
  });
});

describe('codex', () => {
  test.each([
    ['cp *', ['cp']],
    ['git log*', undefined],
    ['git remote', undefined],
    ['npm -v', ['npm', '-v']],
    ['yq *', undefined],
  ])('codexTokens(%s)', (pattern, expected) => {
    expect(codexTokens(entry(pattern))).toEqual(expected);
  });

  test('rules file: header, note comments, one prefix_rule per emitted entry', () => {
    const lines = codexRulesFile(LIST).split('\n');
    expect(lines[0]).toMatch(/^# Generated by `config\/agents\/sync.ts generate`/);
    expect(lines.filter((l) => !l.startsWith('#') && l !== '')).toEqual([
      'prefix_rule(pattern=["cp"], decision="allow")',
      'prefix_rule(pattern=["find"], decision="allow")',
      'prefix_rule(pattern=["jq"], decision="allow")',
      'prefix_rule(pattern=["kubectl", "logs"], decision="allow")',
      'prefix_rule(pattern=["npm", "-v"], decision="allow")',
    ]);
    expect(lines).toContain('# `-exec` runs commands.');
    expect(lines.at(-1)).toBe('');
  });

  test('tokens are Starlark-quoted', () => {
    expect(codexRulesFile({ entries: [{ pattern: 'echo "a\\b"', tier: 'shared' }] })).toContain(
      'prefix_rule(pattern=["echo", "\\"a\\\\b\\""], decision="allow")',
    );
  });
});
